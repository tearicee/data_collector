t.loc[(t.index <= 898) & (t["檢查狀態"] == "待檢查"), "檢查狀態"] = "使用者已檢查 2026-10-02"


def drop(theme, codes=None, source=None):
    global t
    m = t["題材"] == theme
    if codes is not None:
        m &= t["股票代號"].isin(codes)
    if source:
        m &= t["來源"] == source
    t = t[~m]
    return int(m.sum())


def add(parent, theme, code, role="", note="", src="DSL+系統重整", strength="3"):
    global t
    if ((t["題材"] == theme) & (t["股票代號"] == code)).any():
        return
    if "待確認" in note:
        unsure.append((theme, code, info["stock_name"].get(code, ""), note))
    row = {"母題材": parent, "題材": theme, "股票代號": code, "股票名稱": info["stock_name"].get(code, ""),
           "產業": info["industry_category"].get(code, ""), "關聯強度(1-3)": strength, ROLE: role, "備註": note,
           "系統統計_近一年共現次數": "", "保留(Y/N)": "Y", "來源": src, "檢查狀態": DONE}
    t = pd.concat([t, pd.DataFrame([row])], ignore_index=True)


def regroup(old_theme, mapping, parent, keep_note=None):
    """把 old_theme 的列換成 mapping {code: (新題材, 角色, 備註)}；沒列到的保留原樣並標待確認。"""
    codes = list(t.loc[t["題材"] == old_theme, "股票代號"])
    drop(old_theme)
    for c in codes:
        if c in mapping:
            for theme, role, note in ([mapping[c]] if isinstance(mapping[c], tuple) else mapping[c]):
                add(parent, theme, c, role, (note + ("；" if note and keep_note else "") + (keep_note or "")))
        else:
            add(parent, old_theme, c, "", "待確認：未重新分類", src="DSL")


